// Rebuilds Tracer's icon files from assets/icon.svg (24 px and up) and
// assets/icon-small.svg (16 and 20 px, where the hand is too small to read).
// Run with: npx electron scripts/build-icons.mjs
// Writes assets/icon.ico and assets/icon.png for packaging, and
// src/app-icon.mjs for the tray and window icon.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { app, BrowserWindow } from 'electron';

app.setPath('userData', path.join(app.getPath('temp'), 'tracer-icons'));

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SMALL_UP_TO = 20;
const ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256];
// Tray and window images: 16 px at 100% scaling, then larger for higher DPI.
const APP_SIZES = [16, 20, 24, 32, 40, 48, 64];

function svgDataUrl(file) {
  const svg = readFileSync(path.join(root, 'assets', file));
  return `data:image/svg+xml;base64,${svg.toString('base64')}`;
}

async function renderAll(win) {
  const sources = {
    large: svgDataUrl('icon.svg'),
    small: svgDataUrl('icon-small.svg'),
  };
  const sizes = [...new Set([...ICO_SIZES, ...APP_SIZES])];
  const rendered = await win.webContents.executeJavaScript(`(async () => {
    const sources = ${JSON.stringify(sources)};
    const images = {};
    for (const [name, url] of Object.entries(sources)) {
      images[name] = new Image();
      images[name].src = url;
      await images[name].decode();
    }
    const out = {};
    for (const size of ${JSON.stringify(sizes)}) {
      const canvas = document.createElement('canvas');
      canvas.width = canvas.height = size;
      const image = size <= ${SMALL_UP_TO} ? images.small : images.large;
      canvas.getContext('2d').drawImage(image, 0, 0, size, size);
      out[size] = canvas.toDataURL('image/png').split(',')[1];
    }
    return out;
  })()`);
  return new Map(
    Object.entries(rendered).map(([size, base64]) => [Number(size), base64]),
  );
}

// An .ico file whose entries are PNG images, which Windows Vista and later read.
function icoFile(pngs) {
  const header = Buffer.alloc(6 + 16 * pngs.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, data }, index) => {
    const entry = 6 + 16 * index;
    header.writeUInt8(size >= 256 ? 0 : size, entry);
    header.writeUInt8(size >= 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...pngs.map(({ data }) => data)]);
}

function appIconModule(rendered) {
  // Laid out the way oxfmt formats it, so a rebuild leaves no format changes.
  const entries = APP_SIZES.map((size) =>
    [
      '  {',
      `    size: ${size},`,
      `    scaleFactor: ${size / 16},`,
      '    base64:',
      `      '${rendered.get(size)}',`,
      '  },',
    ].join('\n'),
  );
  return [
    '// Generated by scripts/build-icons.mjs from assets/icon.svg and',
    '// assets/icon-small.svg. Do not edit by hand.',
    '// PNG images of the Tracer icon; scaleFactor 1 is 16 px.',
    'export const ICON_PNGS = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false });
  await win.loadURL('data:text/html,<body></body>');
  const rendered = await renderAll(win);
  const png = (size) => Buffer.from(rendered.get(size), 'base64');
  writeFileSync(
    path.join(root, 'assets', 'icon.ico'),
    icoFile(ICO_SIZES.map((size) => ({ size, data: png(size) }))),
  );
  writeFileSync(path.join(root, 'assets', 'icon.png'), png(256));
  writeFileSync(
    path.join(root, 'src', 'app-icon.mjs'),
    appIconModule(rendered),
  );
  console.log(
    `Wrote assets/icon.ico (${ICO_SIZES.join(', ')} px), assets/icon.png, src/app-icon.mjs`,
  );
  app.exit(0);
});
